package de.consorsbank.consumingwebservice.controller;

import de.consorsbank.consumingwebservice.service.AuthorizationService;
import de.consorsbank.consumingwebservice.wsdl.TransactionAuthorizationRequestType;
import de.consorsbank.consumingwebservice.wsdl.TransactionAuthorizationResponseType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.math.BigDecimal;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * REST controller exposing HTTP endpoints to trigger the authorization
 * flow and validate that JAXB-generated classes are available at runtime.
 *
 * <p>Endpoints:
 * <ul>
 *   <li>{@code GET  /api/health}    — proves JAXB class is instantiable</li>
 *   <li>{@code POST /api/authorize} — runs mock authorization using JAXB types</li>
 * </ul>
 * </p>
 *
 * <p>Example curl call:
 * <pre>{@code
 * curl -s -X POST "http://localhost:8080/api/authorize" \
 *      -H "Content-Type: application/json" \
 *      -d '{"accountNumber":"DE89370400440532013000","amount":250.00,"currency":"EUR"}' \
 *      | jq .
 * }</pre></p>
 */
@RestController
@RequestMapping("/api")
public class AuthorizationController {

    private final AuthorizationService authorizationService;

    public AuthorizationController(AuthorizationService authorizationService) {
        this.authorizationService = authorizationService;
    }

    /**
     * Health / readiness check that also confirms the JAXB-generated class can
     * be instantiated without arguments (default no-arg constructor generated by XJC).
     *
     * <p>This endpoint is the simplest possible proof that:
     * <ol>
     *   <li>XJC ran and produced {@code TransactionAuthorizationRequestType.java}</li>
     *   <li>Gradle compiled that file as part of {@code compileJava}</li>
     *   <li>The compiled class is on the runtime classpath</li>
     * </ol>
     * </p>
     */
    @GetMapping("/health")
    public ResponseEntity<Map<String, Object>> health() {
        // Instantiating the JAXB-generated class proves it was compiled and
        // is on the runtime classpath.
        TransactionAuthorizationRequestType req = new TransactionAuthorizationRequestType();

        Map<String, Object> status = new LinkedHashMap<>();
        status.put("status",           "UP");
        status.put("jaxbClassLoaded",  req.getClass().getName());
        status.put("message",
                "JAXB-generated class 'TransactionAuthorizationRequestType' is available on the runtime classpath");
        status.put("generatedBy",      "XJC 4.0.9 via Gradle XJC plugin (genJaxb task)");
        return ResponseEntity.ok(status);
    }

    /**
     * Triggers a mock ESB transaction authorization using JAXB-generated types.
     *
     * @param body JSON body with accountNumber, amount, currency
     * @return JSON representation of the JAXB response object
     */
    @PostMapping("/authorize")
    public ResponseEntity<Map<String, Object>> authorize(@RequestBody Map<String, Object> body) {

        String accountNumber = (String) body.get("accountNumber");
        BigDecimal amount    = new BigDecimal(body.get("amount").toString());
        String currency      = (String) body.get("currency");

        // TransactionAuthorizationResponseType is a JAXB-generated class.
        TransactionAuthorizationResponseType response =
                authorizationService.authorize(accountNumber, amount, currency);

        // Build a plain Map so Jackson can serialize it without requiring
        // a JAXB-aware Jackson module.
        Map<String, Object> result = new LinkedHashMap<>();
        result.put("transactionId",       response.getTransactionId());
        result.put("authorizationStatus", response.getAuthorizationStatus() != null
                ? response.getAuthorizationStatus().value() : null);
        result.put("authorizationCode",   response.getAuthorizationCode());
        result.put("responseTimestamp",   response.getResponseTimestamp() != null
                ? response.getResponseTimestamp().toXMLFormat() : null);
        result.put("errorMessage",        response.getErrorMessage());

        return ResponseEntity.ok(result);
    }
}
